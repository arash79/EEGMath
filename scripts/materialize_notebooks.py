"""Write the validation notebooks. Execute them with nbclient afterwards."""

from __future__ import annotations

from pathlib import Path

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

OUT = Path(__file__).resolve().parents[1] / "notebooks"


def notebook(cells: list) -> nbformat.NotebookNode:
    book = new_notebook(cells=cells, metadata={"kernelspec": {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }})
    return book


def write(name: str, cells: list) -> None:
    OUT.mkdir(exist_ok=True)
    path = OUT / name
    nbformat.write(notebook(cells), path)
    print(path)


